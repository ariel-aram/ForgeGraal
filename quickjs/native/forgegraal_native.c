/* The CA bundle compiled into the binary, generated by tools/gen-ca-bundle.sh. */
extern const char forgegraal_ca_bundle[];

/* ------------------------------------------------------------------ sockets */

#define FG_MAX_SOCKETS 256

typedef struct {
    int in_use;
    int is_tls;
    mbedtls_net_context net;
    mbedtls_ssl_context ssl;
    mbedtls_ssl_config conf;
    mbedtls_x509_crt cacert;
} fg_socket;

/* A fixed table rather than a growing map: ids are indices, an out-of-range or unused id is
   rejected, and JavaScript therefore cannot reach memory by guessing a number. */
static fg_socket fg_sockets[FG_MAX_SOCKETS];
static mbedtls_entropy_context fg_entropy;
static mbedtls_ctr_drbg_context fg_drbg;
static int fg_rng_ready = 0;

static int fg_rng_init(void)
{
    static const char *pers = "forgegraal";
    int ret;

    if (fg_rng_ready) {
        return 0;
    }
    mbedtls_entropy_init(&fg_entropy);
    mbedtls_ctr_drbg_init(&fg_drbg);
    ret = mbedtls_ctr_drbg_seed(&fg_drbg, mbedtls_entropy_func, &fg_entropy,
                                (const unsigned char *) pers, strlen(pers));
    if (ret != 0) {
        return ret;
    }
    fg_rng_ready = 1;
    return 0;
}

static JSValue fg_throw_mbedtls(JSContext *ctx, const char *what, int code)
{
    char buf[128];
    mbedtls_strerror(code, buf, sizeof(buf));
    return JS_ThrowInternalError(ctx, "%s failed: %s (-0x%04x)", what, buf, -code);
}

static fg_socket *fg_socket_get(JSContext *ctx, int32_t id)
{
    if (id < 0 || id >= FG_MAX_SOCKETS || !fg_sockets[id].in_use) {
        JS_ThrowInternalError(ctx, "socket %d does not exist (it was closed, or never opened)", id);
        return NULL;
    }
    return &fg_sockets[id];
}

static void fg_socket_release(fg_socket *sock)
{
    if (!sock->in_use) {
        return;
    }
    if (sock->is_tls) {
        mbedtls_ssl_close_notify(&sock->ssl);
        mbedtls_ssl_free(&sock->ssl);
        mbedtls_ssl_config_free(&sock->conf);
        mbedtls_x509_crt_free(&sock->cacert);
    }
    mbedtls_net_free(&sock->net);
    sock->in_use = 0;
    sock->is_tls = 0;
}

static JSValue fg_connect(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *host;
    char port_str[16];
    int32_t port = 0;
    int is_tls = 0;
    int id = -1;
    int ret;
    fg_socket *sock;

    if (argc < 2) {
        return JS_ThrowTypeError(ctx, "connect(host, port, tls) needs a host and a port");
    }
    host = JS_ToCString(ctx, argv[0]);
    if (!host) {
        return JS_EXCEPTION;
    }
    if (JS_ToInt32(ctx, &port, argv[1])) {
        JS_FreeCString(ctx, host);
        return JS_EXCEPTION;
    }
    if (argc > 2) {
        is_tls = JS_ToBool(ctx, argv[2]);
    }
    snprintf(port_str, sizeof(port_str), "%d", (int) port);

    for (int i = 0; i < FG_MAX_SOCKETS; i++) {
        if (!fg_sockets[i].in_use) {
            id = i;
            break;
        }
    }
    if (id < 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "too many open sockets (limit is %d)", FG_MAX_SOCKETS);
    }

    if (fg_rng_init() != 0) {
        JS_FreeCString(ctx, host);
        return JS_ThrowInternalError(ctx, "could not seed the random number generator");
    }

    sock = &fg_sockets[id];
    memset(sock, 0, sizeof(*sock));
    mbedtls_net_init(&sock->net);

    ret = mbedtls_net_connect(&sock->net, host, port_str, MBEDTLS_NET_PROTO_TCP);
    if (ret != 0) {
        mbedtls_net_free(&sock->net);
        JSValue err = fg_throw_mbedtls(ctx, "connect", ret);
        JS_FreeCString(ctx, host);
        return err;
    }

    if (is_tls) {
        mbedtls_ssl_init(&sock->ssl);
        mbedtls_ssl_config_init(&sock->conf);
        mbedtls_x509_crt_init(&sock->cacert);

        ret = mbedtls_x509_crt_parse(&sock->cacert, (const unsigned char *) forgegraal_ca_bundle,
                                     strlen(forgegraal_ca_bundle) + 1);
        if (ret < 0) {
            goto tls_failed;
        }

        ret = mbedtls_ssl_config_defaults(&sock->conf, MBEDTLS_SSL_IS_CLIENT,
                                          MBEDTLS_SSL_TRANSPORT_STREAM, MBEDTLS_SSL_PRESET_DEFAULT);
        if (ret != 0) {
            goto tls_failed;
        }
        /* Verification is required, not optional: the whole reason for a compiled-in CA bundle
           is to verify properly on a machine whose own store cannot. */
        mbedtls_ssl_conf_authmode(&sock->conf, MBEDTLS_SSL_VERIFY_REQUIRED);
        mbedtls_ssl_conf_ca_chain(&sock->conf, &sock->cacert, NULL);
        mbedtls_ssl_conf_rng(&sock->conf, mbedtls_ctr_drbg_random, &fg_drbg);

        ret = mbedtls_ssl_setup(&sock->ssl, &sock->conf);
        if (ret != 0) {
            goto tls_failed;
        }
        /* SNI: without it Discord's front end serves the wrong certificate. */
        ret = mbedtls_ssl_set_hostname(&sock->ssl, host);
        if (ret != 0) {
            goto tls_failed;
        }
        mbedtls_ssl_set_bio(&sock->ssl, &sock->net, mbedtls_net_send, mbedtls_net_recv, NULL);

        while ((ret = mbedtls_ssl_handshake(&sock->ssl)) != 0) {
            if (ret != MBEDTLS_ERR_SSL_WANT_READ && ret != MBEDTLS_ERR_SSL_WANT_WRITE) {
                goto tls_failed;
            }
        }
        sock->is_tls = 1;
    }

    sock->in_use = 1;
    JS_FreeCString(ctx, host);
    return JS_NewInt32(ctx, id);

tls_failed:
    mbedtls_ssl_free(&sock->ssl);
    mbedtls_ssl_config_free(&sock->conf);
    mbedtls_x509_crt_free(&sock->cacert);
    mbedtls_net_free(&sock->net);
    memset(sock, 0, sizeof(*sock));
    {
        JSValue err = fg_throw_mbedtls(ctx, "TLS handshake", ret);
        JS_FreeCString(ctx, host);
        return err;
    }
}

static JSValue fg_read(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    unsigned char buf[16384];
    int ret;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }

    do {
        ret = sock->is_tls ? mbedtls_ssl_read(&sock->ssl, buf, sizeof(buf))
                           : mbedtls_net_recv(&sock->net, buf, sizeof(buf));
    } while (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE);

    /* A clean close and a zero-length read both mean "peer is done", which is what the
       JavaScript side treats as end of stream. */
    if (ret == MBEDTLS_ERR_SSL_PEER_CLOSE_NOTIFY || ret == 0) {
        return JS_NewUint8ArrayCopy(ctx, buf, 0);
    }
    if (ret < 0) {
        return fg_throw_mbedtls(ctx, "read", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, buf, (size_t) ret);
}

static JSValue fg_write(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;
    fg_socket *sock;
    size_t len = 0;
    uint8_t *data;
    size_t sent = 0;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    sock = fg_socket_get(ctx, id);
    if (!sock) {
        return JS_EXCEPTION;
    }
    data = JS_GetUint8Array(ctx, &len, argv[1]);
    if (!data) {
        return JS_EXCEPTION;
    }

    while (sent < len) {
        int ret = sock->is_tls ? mbedtls_ssl_write(&sock->ssl, data + sent, len - sent)
                               : mbedtls_net_send(&sock->net, data + sent, len - sent);
        if (ret == MBEDTLS_ERR_SSL_WANT_READ || ret == MBEDTLS_ERR_SSL_WANT_WRITE) {
            continue;
        }
        if (ret <= 0) {
            return fg_throw_mbedtls(ctx, "write", ret);
        }
        sent += (size_t) ret;
    }
    return JS_UNDEFINED;
}

static JSValue fg_close(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t id;

    if (JS_ToInt32(ctx, &id, argv[0])) {
        return JS_EXCEPTION;
    }
    /* Closing twice is not an error: a JavaScript stream may well destroy() after the peer
       already went away. */
    if (id >= 0 && id < FG_MAX_SOCKETS && fg_sockets[id].in_use) {
        fg_socket_release(&fg_sockets[id]);
    }
    return JS_UNDEFINED;
}

/* ------------------------------------------------------------------- crypto */

static mbedtls_md_type_t fg_md_type(const char *name)
{
    if (!strcmp(name, "sha256")) return MBEDTLS_MD_SHA256;
    if (!strcmp(name, "sha1")) return MBEDTLS_MD_SHA1;
    if (!strcmp(name, "sha512")) return MBEDTLS_MD_SHA512;
    if (!strcmp(name, "md5")) return MBEDTLS_MD_MD5;
    return MBEDTLS_MD_NONE;
}

static JSValue fg_hash(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *name;
    size_t len = 0;
    uint8_t *data;
    unsigned char out[64];
    const mbedtls_md_info_t *info;
    mbedtls_md_type_t type;
    int ret;

    name = JS_ToCString(ctx, argv[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    type = fg_md_type(name);
    if (type == MBEDTLS_MD_NONE) {
        JSValue err = JS_ThrowInternalError(
            ctx,
            "hash algorithm '%s' is not available in this runtime (sha1, sha256, sha512 and md5 are). "
            "Substituting a different algorithm would silently produce values that do not verify.",
            name);
        JS_FreeCString(ctx, name);
        return err;
    }
    JS_FreeCString(ctx, name);

    data = JS_GetUint8Array(ctx, &len, argv[1]);
    if (!data) {
        return JS_EXCEPTION;
    }
    info = mbedtls_md_info_from_type(type);
    ret = mbedtls_md(info, data, len, out);
    if (ret != 0) {
        return fg_throw_mbedtls(ctx, "hash", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, out, mbedtls_md_get_size(info));
}

static JSValue fg_hmac(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    const char *name;
    size_t key_len = 0, data_len = 0;
    uint8_t *key, *data;
    unsigned char out[64];
    const mbedtls_md_info_t *info;
    mbedtls_md_type_t type;
    int ret;

    name = JS_ToCString(ctx, argv[0]);
    if (!name) {
        return JS_EXCEPTION;
    }
    type = fg_md_type(name);
    if (type == MBEDTLS_MD_NONE || type == MBEDTLS_MD_MD5) {
        JSValue err = JS_ThrowInternalError(
            ctx, "HMAC algorithm '%s' is not available in this runtime (sha1, sha256 and sha512 are).",
            name);
        JS_FreeCString(ctx, name);
        return err;
    }
    JS_FreeCString(ctx, name);

    key = JS_GetUint8Array(ctx, &key_len, argv[1]);
    data = JS_GetUint8Array(ctx, &data_len, argv[2]);
    if (!key || !data) {
        return JS_EXCEPTION;
    }
    info = mbedtls_md_info_from_type(type);
    ret = mbedtls_md_hmac(info, key, key_len, data, data_len, out);
    if (ret != 0) {
        return fg_throw_mbedtls(ctx, "hmac", ret);
    }
    return JS_NewUint8ArrayCopy(ctx, out, mbedtls_md_get_size(info));
}

static JSValue fg_random_bytes(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    int32_t len;
    unsigned char *buf;
    int ret;
    JSValue out;

    if (JS_ToInt32(ctx, &len, argv[0]) || len < 0) {
        return JS_ThrowTypeError(ctx, "randomBytes(length) needs a non-negative length");
    }
    if (fg_rng_init() != 0) {
        return JS_ThrowInternalError(ctx, "could not seed the random number generator");
    }
    buf = js_malloc(ctx, len ? (size_t) len : 1);
    if (!buf) {
        return JS_EXCEPTION;
    }
    ret = mbedtls_ctr_drbg_random(&fg_drbg, buf, (size_t) len);
    if (ret != 0) {
        js_free(ctx, buf);
        return fg_throw_mbedtls(ctx, "randomBytes", ret);
    }
    out = JS_NewUint8ArrayCopy(ctx, buf, (size_t) len);
    js_free(ctx, buf);
    return out;
}

/* -------------------------------------------------------------- compression */

static JSValue fg_zlib(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv,
                       int compress, int raw)
{
    size_t len = 0;
    uint8_t *data = JS_GetUint8Array(ctx, &len, argv[0]);
    mz_ulong out_len;
    unsigned char *out;
    JSValue result;
    int ret;

    if (!data) {
        return JS_EXCEPTION;
    }

    if (compress) {
        out_len = mz_compressBound((mz_ulong) len);
        out = js_malloc(ctx, out_len ? out_len : 1);
        if (!out) {
            return JS_EXCEPTION;
        }
        ret = mz_compress2(out, &out_len, data, (mz_ulong) len, MZ_DEFAULT_COMPRESSION);
        if (ret != MZ_OK) {
            js_free(ctx, out);
            return JS_ThrowInternalError(ctx, "deflate failed (%d)", ret);
        }
    } else {
        /* Inflating needs a guess at the output size; grow until it fits rather than
           capping, so a large gateway frame is not silently truncated. */
        size_t capacity = len * 4 + 1024;
        for (;;) {
            out = js_malloc(ctx, capacity);
            if (!out) {
                return JS_EXCEPTION;
            }
            out_len = (mz_ulong) capacity;
            ret = mz_uncompress(out, &out_len, data, (mz_ulong) len);
            if (ret == MZ_OK) {
                break;
            }
            js_free(ctx, out);
            if (ret != MZ_BUF_ERROR || capacity > (64u << 20)) {
                return JS_ThrowInternalError(ctx, "inflate failed (%d)", ret);
            }
            capacity *= 4;
        }
    }

    result = JS_NewUint8ArrayCopy(ctx, out, (size_t) out_len);
    js_free(ctx, out);
    (void) raw;
    return result;
}

static JSValue fg_inflate(JSContext *ctx, JSValueConst t, int argc, JSValueConst *argv)
{
    return fg_zlib(ctx, t, argc, argv, 0, argc > 1 ? JS_ToBool(ctx, argv[1]) : 0);
}

static JSValue fg_deflate(JSContext *ctx, JSValueConst t, int argc, JSValueConst *argv)
{
    return fg_zlib(ctx, t, argc, argv, 1, argc > 1 ? JS_ToBool(ctx, argv[1]) : 0);
}

/* ---------------------------------------------------------------------- text */

static JSValue fg_encode_utf8(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    size_t len;
    const char *str = JS_ToCStringLen(ctx, &len, argv[0]);
    JSValue out;

    if (!str) {
        return JS_EXCEPTION;
    }
    out = JS_NewUint8ArrayCopy(ctx, (const uint8_t *) str, len);
    JS_FreeCString(ctx, str);
    return out;
}

static JSValue fg_decode_utf8(JSContext *ctx, JSValueConst this_val, int argc, JSValueConst *argv)
{
    size_t len = 0;
    uint8_t *data = JS_GetUint8Array(ctx, &len, argv[0]);

    if (!data) {
        return JS_EXCEPTION;
    }
    return JS_NewStringLen(ctx, (const char *) data, len);
}

