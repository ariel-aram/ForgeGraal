/*
 * ForgeGraal's native layer for quickjs-ng, in C.
 *
 * This is the same surface the Rust host (`runtime/`) provides, and deliberately so: both install
 * `globalThis.__forgegraal_native` with identical function names and shapes, so
 * `quickjs/runtime/native-modules.js` runs unchanged on either. The JavaScript above does not know
 * or care which backend is underneath.
 *
 * It exists because Rust cannot go low enough. Rust's standard library for 32-bit Windows imports
 * ProcessPrng (Windows 10), WaitOnAddress (Windows 8) and the api-ms-win-core-synch API set
 * (Windows 7), so the Rust host cannot serve Windows XP or Vista at all. This file uses only
 * Winsock 2 and CryptoAPI, both present since Windows 95/NT4, which is what makes XP reachable.
 *
 * TLS is mbedTLS, chosen for the same reason as everything else here: it is portable C with no
 * dependency on a modern platform, and its certificate verification uses a CA bundle compiled into
 * the binary rather than the operating system's store -- the store on a machine this old is a
 * decade stale and would reject Discord outright.
 *
 * Compression is miniz, a single public-domain file with the zlib API.
 */

